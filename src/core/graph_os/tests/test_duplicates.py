def test_layout_and_comments_never_change_a_fingerprint():
    from graph_os.extractors import code_python, code_ts

    def hashes(result, label):
        node = next(n for n in result.nodes if n.label == label)
        return node.ast_hash, node.content_hash

    spaced = MONEY.replace("const rounded =", "const   rounded =\n   ")
    assert hashes(code_ts.extract("a.ts", MONEY), "formatPrice") == hashes(
        code_ts.extract("b.ts", "// header\n" + spaced), "formatPrice"
    )
    assert hashes(code_python.extract("a.py", PY_A), "chunked") == hashes(
        code_python.extract("b.py", PY_B), "chunked"
    )


def test_small_bodies_carry_no_fingerprint_and_every_symbol_has_its_end():
    from graph_os.extractors import code_go, code_shell, code_ts

    tiny = next(n for n in code_ts.extract("p.ts", RENAMED).nodes if n.label == "tiny")
    clamp = next(
        n for n in code_go.extract("c.go", GO.format(name="x")).nodes if n.label == "Clamp"
    )
    script = "#!/usr/bin/env bash\nhello() {\n  echo hi\n}\n"
    hello = next(n for n in code_shell.extract("s.sh", script).nodes if n.label == "hello")

    assert (tiny.ast_hash, tiny.content_hash, tiny.end_line) == (None, None, 9)
    assert (clamp.start_line, clamp.end_line) == (3, 17)
    assert clamp.signature == "func Clamp(value, low, high int) int"
    assert (hello.start_line, hello.end_line, hello.ast_hash) == (2, 4, None)


