def _labels(group: dict) -> set[tuple[str, str]]:
    return {
        (
            member["uid"].split(":", 2)[2].split("::")[0],
            member["uid"].split("::")[-1].split(".")[-1],
        )
        for member in group["members"]
    }


def _group_with(groups: list[dict], file_path: str, label: str) -> dict:
    return next(g for g in groups if (file_path, label) in _labels(g))


def test_an_exact_copy_and_a_renamed_copy_join_one_group(call):
    groups = call("cos_graph_duplicates")["data"]["groups"]
    price = _group_with(groups, "packages/shared/src/money.ts", "formatPrice")

    assert _labels(price) == {
        ("packages/shared/src/money.ts", "formatPrice"),
        ("apps/web/src/lib/money.ts", "formatPrice"),
        ("apps/mobile/src/utils/price.ts", "formatCost"),
    }
    assert price["clone_type"] == "renamed"


