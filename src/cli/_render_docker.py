"""Per-language Dockerfile skeletons and the .dockerignore beside them.

Base images and their idioms move on the upstream registries' clock, not the
project's; keeping them here means bumping a base image never opens the module
that composes AGENTS.md. Pure data plus two lookups — no world required.
"""

