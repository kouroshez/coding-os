_DOCKERIGNORE = """\
# Auto-generated by coding-os `cos init` — consumer-owned.
.git
.gitignore
**/.coding-os
**/node_modules
**/__pycache__
**/.venv
**/target
**/dist
**/*.log
**/.env
**/.env.*
Dockerfile
.dockerignore
"""


def render_dockerfile(language: str) -> str:
    """Multi-stage, non-root Dockerfile skeleton for a backend language, or "".

    The build stage carries the toolchain, the runtime stage only the artifact;
    the runtime runs as a non-root user with a healthcheck. Returns "" for a
    language with no skeleton (frontend/mobile/library never get one).
    """
    return _DOCKERFILE_SKELETONS.get(language, "")


def render_dockerignore() -> str:
    """The .dockerignore shipped beside a generated Dockerfile."""
    return _DOCKERIGNORE
