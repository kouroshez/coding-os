"""Clone-ready adapter dirs: links stay inside the repo, user edits stay theirs.

Spec: docs/architecture/adr/0010-consumer-distribution-version-gate.md § Amendment.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from cli import _localize_links as localize_mod
from cli._init_git import _RUNTIME_GITIGNORE_BLOCK, ensure_gitignore
from cli._localize_links import delocalize, link_form, localize
from cli._resources import core_dir

RULE = core_dir("rules", "anti-overengineering.md")
HOOK = core_dir("hooks", "record-verify.sh")
LIBRARY = core_dir("hooks", "cos-env.sh")


@pytest.fixture()
def consumer(tmp_path: Path) -> Path:
    project = tmp_path / "consumer"
    for sub in ("hooks", "rules"):
        (project / ".claude" / sub).mkdir(parents=True)
    (project / ".coding-os").mkdir()
    (project / ".claude/hooks/record-verify.sh").symlink_to(HOOK)
    (project / ".claude/hooks/cos-env.sh").symlink_to(LIBRARY)
    (project / ".claude/rules/anti-overengineering.md").symlink_to(RULE)
    return project


def _outside(project: Path) -> list[str]:
    root = project.resolve()
    return [
        str(p) for p in project.rglob("*") if p.is_symlink() and root not in p.resolve().parents
    ]


def test_localize_keeps_every_link_inside_the_repo(consumer: Path) -> None:
    report = localize(consumer, ["claude"])

    hook = consumer / ".claude/hooks/record-verify.sh"
    assert os.readlink(hook) == "../../.coding-os/hook-shim.sh"
    assert (consumer / ".coding-os/hook-shim.sh").is_file()
    assert not (consumer / ".claude/hooks/cos-env.sh").exists()  # sourced, never shimmed
    rule = consumer / ".claude/rules/anti-overengineering.md"
    assert not rule.is_symlink() and rule.read_bytes() == RULE.read_bytes()
    assert _outside(consumer) == []
    assert (report.shimmed, report.copied) == (1, 1)


def test_delocalize_restores_install_links(consumer: Path) -> None:
    localize(consumer, ["claude"])

    assert delocalize(consumer) == []

    assert (consumer / ".claude/hooks/record-verify.sh").resolve() == HOOK.resolve()
    assert (consumer / ".claude/hooks/cos-env.sh").resolve() == LIBRARY.resolve()
    assert (consumer / ".claude/rules/anti-overengineering.md").resolve() == RULE.resolve()


def test_an_edited_copy_is_kept_and_survives_an_overwriting_step(consumer: Path) -> None:
    localize(consumer, ["claude"])
    rule = consumer / ".claude/rules/anti-overengineering.md"
    rule.write_text("my version\n", encoding="utf-8")

    with link_form(consumer, ["claude"]) as kept:
        assert kept == [".claude/rules/anti-overengineering.md"]
        rule.symlink_to(RULE)  # an installer's `ln -sf` writing over the path

    assert rule.read_text(encoding="utf-8") == "my version\n"
    entries = json.loads((consumer / ".coding-os/managed-files.json").read_text())["entries"]
    assert entries[".claude/rules/anti-overengineering.md"]["kind"] == "owned"


def test_in_coding_os_itself_links_become_relative(consumer: Path, monkeypatch) -> None:
    monkeypatch.setattr(localize_mod, "CODING_OS_ROOT", consumer)

    localize(consumer, ["claude"])

    rule = consumer / ".claude/rules/anti-overengineering.md"
    assert rule.is_symlink() and not os.readlink(rule).startswith("/")
    assert rule.resolve() == RULE.resolve()


def test_gitignore_migration_stops_ignoring_the_adapter_dirs(tmp_path: Path) -> None:
    legacy = (
        "node_modules/\n.coding-os/*\n!.coding-os/rag-config.yaml\n\n"
        "# Rendered agent adapters — regenerated by `cos update`; they hold\n"
        "# machine-absolute symlink paths that do not survive a clone.\n"
        ".claude/\n.codex/\n.mcp.json\n"
    )
    (tmp_path / ".gitignore").write_text(legacy, encoding="utf-8")

    assert ensure_gitignore(tmp_path) is True
    lines = (tmp_path / ".gitignore").read_text(encoding="utf-8").splitlines()

    assert not {".claude/", ".codex/", ".mcp.json"} & set(lines)
    assert {"!.coding-os/hook-shim.sh", ".claude/settings.local.json", "node_modules/"} <= set(
        lines
    )
    assert ensure_gitignore(tmp_path) is False
    assert ".claude/settings.local.json" in _RUNTIME_GITIGNORE_BLOCK


def test_a_library_skill_is_copied_in_without_its_provenance(
    consumer: Path, tmp_path: Path, monkeypatch
) -> None:
    library = tmp_path / "library"
    (library / "trader").mkdir(parents=True)
    (library / "trader" / "SKILL.md").write_text("---\nname: trader\n---\n", encoding="utf-8")
    (library / "trader" / ".provenance.json").write_text('{"path": "/Users/x"}', encoding="utf-8")
    monkeypatch.setenv("COS_USER_SKILLS_DIR", str(library))
    (consumer / ".claude/skills").mkdir()
    (consumer / ".claude/skills/trader").symlink_to(library / "trader")

    localize(consumer, ["claude"])
    copied = consumer / ".claude/skills/trader"
    assert not copied.is_symlink() and (copied / "SKILL.md").is_file()
    assert not (copied / ".provenance.json").exists()

    delocalize(consumer)
    assert copied.is_symlink() and copied.resolve() == (library / "trader").resolve()


def test_a_project_own_skill_is_linked_relatively_to_its_in_repo_source(
    consumer: Path, tmp_path: Path, monkeypatch
) -> None:
    from cli._skill_project import _community_source

    own = consumer / "skills" / "redline"
    own.mkdir(parents=True)
    (own / "SKILL.md").write_text("---\nname: redline\n---\n", encoding="utf-8")
    library = tmp_path / "library"
    (library / "redline").mkdir(parents=True)
    (library / "redline" / ".provenance.json").write_text(
        '{"source": "skills/redline"}', encoding="utf-8"
    )
    monkeypatch.setenv("COS_USER_SKILLS_DIR", str(library))

    assert _community_source(consumer, "redline") == own.resolve()
    (consumer / ".claude/skills").mkdir()
    (consumer / ".claude/skills/redline").symlink_to(own.resolve())
    localize(consumer, ["claude"])

    link = consumer / ".claude/skills/redline"
    assert os.readlink(link) == "../../skills/redline"
